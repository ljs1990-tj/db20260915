-- 댓글 테이블 (BOARD_COMMENT)
-- 댓글번호(COMMENTNO), 댓글내용(CONTENTS), 작성자(USERID), 
-- 작성일(CDATETIME), 수정일(UDATETIME)
DROP TABLE BOARD_COMMENT;
CREATE TABLE BOARD_COMMENT(
    COMMENTNO NUMBER PRIMARY KEY,
    BOARDNO NUMBER,
    CONTENTS VARCHAR2(200),
    USERID VARCHAR2(100),
    CDATETIME DATE,
    UDATETIME DATE
);

CREATE SEQUENCE COMMENT_SEQ
    INCREMENT BY 1
    START WITH 1;


