-- 각 게시글별 댓글 수 구하기(없으면 0으로 출력)

SELECT 
    B.BOARDNO, TITLE, B.CONTENTS, COUNT(C.COMMENTNO)
FROM BOARD B
LEFT JOIN BOARD_COMMENT C ON B.BOARDNO = C.BOARDNO
GROUP BY B.BOARDNO, TITLE, B.CONTENTS;



SELECT 
    B.*, NVL(C_CNT, 0) AS 댓글개수
FROM BOARD B
LEFT JOIN (
    SELECT BOARDNO, COUNT(*) AS C_CNT
    FROM BOARD_COMMENT
    GROUP BY BOARDNO
) T ON B.BOARDNO = T.BOARDNO;

