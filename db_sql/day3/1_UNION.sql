-- 주의점
-- 1. 컬럼의 개수가 동일해야 한다.
-- 2. 컬럼의 타입도 동일해야 한다.
-- 3. 컬럼이름(별칭)은 먼저 나오는 값을 기준으로 출력이 된다.
-- 4. 정렬(ORDER BY)는 맨 마지막에 작성. 첫번째 쿼리 컬럼을 기준으로 한다.

SELECT AVG(STU_HEIGHT) 
FROM STUDENT
UNION
SELECT STU_NAME 
FROM STUDENT; -- 데이터 타입이 달라서 오류


SELECT AVG(STU_HEIGHT) 
FROM STUDENT
UNION
SELECT MAX(STU_HEIGHT), MIN(STU_HEIGHT)
FROM STUDENT; -- 컬럼의 개수 달라서 오류


SELECT AVG(STU_HEIGHT) AS QQQ, COUNT(STU_HEIGHT) 
FROM STUDENT
UNION
SELECT MAX(STU_HEIGHT) AS ZZZ, MIN(STU_HEIGHT) AS HHH
FROM STUDENT; -- 컬럼의 이름은 첫번째 쿼리 이름을 따른다.


SELECT AVG(STU_HEIGHT) AS QQQ, COUNT(STU_HEIGHT) 
FROM STUDENT
UNION
SELECT MAX(STU_HEIGHT) AS ZZZ, MIN(STU_HEIGHT) AS HHH
FROM STUDENT
ORDER BY QQQ; -- 정렬은 맨 마지막에, 합쳐진 이후에 한다.


-- 1. 학생들의 평균 점수 구하기
SELECT 
    STU_NAME, AVG(ENR_GRADE) AS AVG_GRADE
FROM STUDENT S
INNER JOIN ENROL E ON S.STU_NO = E.STU_NO
GROUP BY STU_NAME;

-- 2. 전체 평균 구하기
SELECT AVG(ENR_GRADE)
FROM ENROL;
-- 3. 합치기

SELECT 
    STU_NAME, AVG(ENR_GRADE) AS AVG_GRADE, 1 AS ORDERKEY
FROM STUDENT S
INNER JOIN ENROL E ON S.STU_NO = E.STU_NO
GROUP BY STU_NAME
UNION
SELECT '전체평균', AVG(ENR_GRADE), 2 AS ORDERKEY
FROM ENROL
ORDER BY ORDERKEY;

SELECT STU_NAME, AVG_GRADE
FROM (
    SELECT 
    STU_NAME, AVG(ENR_GRADE) AS AVG_GRADE, 1 AS ORDERKEY
    FROM STUDENT S
    INNER JOIN ENROL E ON S.STU_NO = E.STU_NO
    GROUP BY STU_NAME
    UNION
    SELECT '전체평균', AVG(ENR_GRADE), 2 AS ORDERKEY
    FROM ENROL
    ORDER BY ORDERKEY
);

