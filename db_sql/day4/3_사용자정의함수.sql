CREATE OR REPLACE FUNCTION GENDER_CHECK(I_VALUE VARCHAR2)
RETURN VARCHAR2
IS
    O_VALUE VARCHAR2(10);
BEGIN
    IF LENGTH(I_VALUE) != 13 THEN
        O_VALUE := '알수없음';       
    ELSIF SUBSTR(I_VALUE, 7, 1) IN (1,3) THEN
         O_VALUE := '남자';
    ELSIF SUBSTR(I_VALUE, 7, 1) IN (2,4) THEN         
        O_VALUE := '여자';
    ELSE
        O_VALUE := '알수없음';
    END IF;
        
    RETURN O_VALUE;
END;
/



CREATE OR REPLACE FUNCTION GENDER_CHECK(I_VALUE VARCHAR2)
RETURN VARCHAR2
IS
    O_VALUE VARCHAR2(20);
BEGIN
    O_VALUE := '알수없음'; 
    IF LENGTH(I_VALUE) = 13 AND SUBSTR(I_VALUE, 7, 1) IN (1,3) THEN
         O_VALUE := '남자';
    ELSIF LENGTH(I_VALUE) = 13 AND SUBSTR(I_VALUE, 7, 1) IN (2,4) THEN         
        O_VALUE := '여자';
    END IF;       
    RETURN O_VALUE;
END;
/

