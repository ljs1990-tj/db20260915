SELECT 
    S.STU_NO, STU_NAME, STU_DEPT, ENR_GRADE,
    SCORE_GRADE(ENR_GRADE) AS GRADE
    -- 90~100 -> A, 80~89 -> B, 70~79 -> C, 60~69 -> D
    -- 나머지 F, 음수나 100초과는 없다고 가정하고 하세요
FROM STUDENT S 
INNER JOIN ENROL E ON S.STU_NO = E.STU_NO;

CREATE OR REPLACE FUNCTION SCORE_GRADE(I_VALUE NUMBER)
RETURN VARCHAR2
IS
    O_VALUE VARCHAR2(20);
BEGIN
    IF I_VALUE BETWEEN 90 AND 100 THEN
        O_VALUE := 'A';
    ELSIF I_VALUE >= 80 THEN
        O_VALUE := 'B';
    ELSIF I_VALUE >= 70 THEN
        O_VALUE := 'C';
    ELSIF I_VALUE >= 60 THEN
        O_VALUE := 'D';
    ELSE 
        O_VALUE := 'F';
    END IF;
    RETURN O_VALUE;
END;
/




