SELECT * FROM ENROL;

-- 학번 => STUDENT, ENROL, 
-- (이름, 학과) => STUDENT, 점수 => ENROL, 과목명 => SUBJECT

SELECT 
    S.STU_NO, STU_NAME, STU_DEPT, ENR_GRADE, SUB_NAME
FROM STUDENT S
INNER JOIN ENROL E ON S.STU_NO = E.STU_NO
INNER JOIN SUBJECT SUB ON E.SUB_NO = SUB.SUB_NO;

