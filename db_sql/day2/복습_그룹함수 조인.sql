-- 그룹 함수
-- AVG, MAX, MIN, COUNT, SUM

-- 학생들의 전체 키 평균
SELECT 
    AVG(STU_HEIGHT) 
FROM STUDENT;

-- 학과별 학생들의 전체 키 평균
SELECT 
    STU_DEPT,
    AVG(STU_HEIGHT) 
FROM STUDENT
GROUP BY STU_DEPT;

-- 학과별 학생들의 키 평균
-- 단, 170 이상만 대상으로 한다 => WHERE
-- 평균키가 175 이상인 학과+평균키만 출력 => HAVING
SELECT 
    STU_DEPT,
    AVG(STU_HEIGHT) 
FROM STUDENT
WHERE STU_HEIGHT >= 170
GROUP BY STU_DEPT
HAVING AVG(STU_HEIGHT) >= 175;

-- COUNT는 컬럼명을 넣었을 때 NULL값은 제외하고 카운트

SELECT 
    COUNT(*),
    COUNT(STU_NO),
    COUNT(STU_HEIGHT)
FROM STUDENT;

