-- OUTER 조인 (LEFT 위주)

SELECT *
FROM STUDENT S 
INNER JOIN ENROL E ON S.STU_NO = E.STU_NO;

SELECT *
FROM STUDENT S 
LEFT JOIN ENROL E ON S.STU_NO = E.STU_NO;

-- 각 학생별 시험평균점수 출력, 시험은 안본 학생은 '점수없음' 출력
SELECT 
    S.STU_NO, STU_NAME,
    NVL(TO_CHAR(AVG(ENR_GRADE)), '점수없음')
FROM STUDENT S 
LEFT JOIN ENROL E ON S.STU_NO = E.STU_NO
GROUP BY S.STU_NO, STU_NAME;

-- 각 학생들이 본 시험의 수 출력
-- 시험을 안본친구들 0으로 출력
SELECT
    S.STU_NO, STU_NAME,
    COUNT(ENR_GRADE)
FROM STUDENT S
LEFT JOIN ENROL E ON S.STU_NO = E.STU_NO
GROUP BY S.STU_NO, STU_NAME;


-- PROFESSOR
SELECT * FROM PROFESSOR;
SELECT * FROM STU;

-- 1. 학생이름, 담당교수이름 출력. 담당교수 없으면 '담당없음' 으로 출력
SELECT 
    S.NAME, NVL(P.NAME, '담당없음')
FROM STU S
LEFT JOIN PROFESSOR P ON S.PROFNO = P.PROFNO;
-- 2. 각 교수가 담당하고 있는 학생의 수 출력. 없으면 0으로 출력
SELECT 
    P.PROFNO, P.NAME,
    COUNT(STUNO)
FROM PROFESSOR P
LEFT JOIN STU S ON P.PROFNO = S.PROFNO
GROUP BY P.PROFNO, P.NAME;

