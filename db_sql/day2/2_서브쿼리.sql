-- 서브쿼리 : 쿼리안에 또 다른 쿼리
-- STUDENT
SELECT MAX(STU_HEIGHT)
FROM STUDENT;

SELECT *
FROM STUDENT
WHERE STU_HEIGHT = (
    SELECT MAX(STU_HEIGHT)
    FROM STUDENT
);

-- UNION => 나중에 자세히, 결과 합치는 기능
SELECT MAX(STU_HEIGHT) AS HEIGHT
FROM STUDENT
UNION
SELECT MIN(STU_HEIGHT) AS HEIGHT
FROM STUDENT;

-- 2개이상의 레코드 조건절에서 서브쿼리
SELECT *
FROM STUDENT
WHERE STU_HEIGHT IN (
    SELECT MAX(STU_HEIGHT) AS HEIGHT
    FROM STUDENT
    UNION
    SELECT MIN(STU_HEIGHT) AS HEIGHT
    FROM STUDENT
);

--
SELECT    
    STU_DEPT,
    MAX(STU_HEIGHT)
FROM STUDENT
GROUP BY STU_DEPT;

-- 아래처럼 하면 다른 학과의 동일 키를 가진 학생도 조회될 수 있다.
SELECT *
FROM STUDENT
WHERE STU_HEIGHT IN (
    SELECT    
        MAX(STU_HEIGHT)
    FROM STUDENT
    GROUP BY STU_DEPT
);

