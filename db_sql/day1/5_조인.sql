-- 조인은 꼭 값이 같은 컬럼끼리 하는건 아니다.
-- 사원들의 급여 등급 출력(사번, 이름, 급여, 급여등급 출력)
SELECT 
    EMPNO, ENAME, SAL, GRADE
FROM EMP E
INNER JOIN SALGRADE S ON E.SAL BETWEEN LOSAL AND HISAL;

-- 각 부서별 급여 평균 등급 출력
-- (부서번호, 부서이름, 급여 등급 출력)

SELECT 
    E.DEPTNO, DNAME,
    AVG(GRADE)
FROM EMP E
INNER JOIN SALGRADE S ON E.SAL BETWEEN LOSAL AND HISAL
INNER JOIN DEPT D ON E.DEPTNO = D.DEPTNO
GROUP BY E.DEPTNO, DNAME;





